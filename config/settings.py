def env_bool(nome, padrao=False):
    valor = os.getenv(nome)

    if valor is None:
        return padrao

    return valor.strip().lower() in {
        "1",
        "true",
        "yes",
        "on",
    }


def env_list(nome, padrao=""):
    valor = os.getenv(nome, padrao)

    return [
        item.strip()
        for item in valor.split(",")
        if item.strip()
    ]


